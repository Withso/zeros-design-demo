// Builds the "Token build" style source: reads tokens.json beside this file
// and writes CSS to the path Zeros passes in ZEROS_DESIGN_STYLE_OUTPUT
// (repository-relative). Zeros runs it while Design is open and again when a
// file in styles/build changes. To run it by hand from the repository root:
//   ZEROS_DESIGN_STYLE_OUTPUT=.zeros/design-styles/tokens.css node styles/build/build-tokens.mjs
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.env.ZEROS_WORKTREE_PATH || process.cwd();
const output = path.resolve(root, process.env.ZEROS_DESIGN_STYLE_OUTPUT || ".zeros/design-styles/tokens.css");
const tokens = JSON.parse(readFileSync(path.join(here, "tokens.json"), "utf8"));

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([name, value]) => `  --ds-${name}: ${value};`).join("\n")}\n}`;
const prefixed = (prefix, values) => Object.entries(values).map(([name, value]) => [`${prefix}-${name}`, value]);

const css = [
  `/* Generated by styles/build/build-tokens.mjs from tokens.json. */`,
  block(":root", [
    ...Object.entries(tokens.color.light),
    ...prefixed("space", tokens.space),
    ...prefixed("radius", tokens.radius),
  ]),
  block('[data-theme="dark"]', Object.entries(tokens.color.dark)),
  `.ds-surface { display: flex; flex-direction: column; gap: var(--ds-space-md); padding: var(--ds-space-lg); border: 1px solid var(--ds-line); border-radius: var(--ds-radius-lg); background-color: var(--ds-surface); color: var(--ds-ink); }`,
  `.ds-muted { color: var(--ds-muted); font-size: 13px; line-height: 18px; }`,
  `.ds-pill { display: inline-flex; align-items: center; height: 26px; padding: 0 var(--ds-space-md); border-radius: 999px; background-color: var(--ds-accent); color: var(--ds-on-accent); font-size: 12px; font-weight: 600; }`,
  `.ds-pill--soft { background-color: var(--ds-accent-wash); color: var(--ds-ink); }`,
  `.ds-meter { height: 8px; border-radius: 999px; background-color: var(--ds-line); overflow: hidden; }`,
  `.ds-meter-fill { display: block; height: 100%; border-radius: inherit; background-color: var(--ds-accent); }`,
].join("\n\n") + "\n";

mkdirSync(path.dirname(output), { recursive: true });
const temporary = `${output}.tmp-${process.pid}`;
writeFileSync(temporary, css);
renameSync(temporary, output);
console.log(`Wrote ${path.relative(root, output)} (${css.length} bytes)`);
